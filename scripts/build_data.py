"""Wrap polimill_data/ into assets/js/data.js so the page opens without a server.

Values are copied verbatim; nothing is recomputed or rewritten here.
"""
import csv
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "polimill_data"

data = json.loads((SRC / "polimill_data.json").read_text(encoding="utf-8"))
with open(SRC / "0_all_news_699.csv", encoding="utf-8-sig", newline="") as f:
    rows = list(csv.reader(f))
header, body = rows[0], rows[1:]
assert header == ["日付", "テーマ（暫定分類）", "タイトル", "出典", "URL"], header
data["news"] = [
    {"date": r[0], "theme": r[1], "title": r[2], "source": r[3], "url": r[4]} for r in body
]

out = ROOT / "assets" / "js" / "data.js"
out.write_text(
    "/* generated by scripts/build_data.py from polimill_data/ — do not edit */\n"
    "window.PM_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print(f"wrote {out} (news={len(data['news'])}, milestones={len(data['milestones'])})")
